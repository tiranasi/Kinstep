export function translate(locale: Locale, value: string): string {
  if (locale === "zh") return value;
  if (Object.hasOwn(english, value)) return english[value];
  const updates = [
    /^(.+)：(已确认缴费|检查已完成|报告已拿到|已确认服药|本次未服|10分钟后再提醒)$/,
    /^已确认(.+?)(，材料已保存)?$/,
    /^已核对(.+)的服药安排$/,
    /^已启用(.+)的服药提醒$/,
  ] as const;
  const [item, document, medication, reminder] = updates.map((pattern) => value.match(pattern));
  const name = (text: string) => (Object.hasOwn(english, text) ? english[text] : text);
  if (item) return `${name(item[1])} · ${name(item[2])}`;
  if (document) return `${document[2] ? "Saved" : "Confirmed"} · ${name(document[1])}`;
  if (medication) return `Medication plan reviewed · ${name(medication[1])}`;
  if (reminder) return `Reminders on · ${name(reminder[1])}`;
  return value;
}
